// Render the About-page equations from LaTeX to SVG with MathJax.
//
//   cd tools/equations && npm install && npm run render
//
// Input:  crates/stellar-app/equations/equations.json   [{ "id": ..., "tex": ... }]
// Output: crates/stellar-app/assets/equations/<id>.svg  (white glyphs; tinted in the app)
//         crates/stellar-app/src/equations.rs           (generated registry, embeds the SVGs)
//
// The SVGs contain glyph outlines as paths (no fonts needed). Sizes are
// converted from MathJax's `ex` units to pixels so any SVG renderer can
// rasterise them.

const fs = require('fs');
const path = require('path');
const { mathjax } = require('mathjax-full/js/mathjax.js');
const { TeX } = require('mathjax-full/js/input/tex.js');
const { SVG } = require('mathjax-full/js/output/svg.js');
const { liteAdaptor } = require('mathjax-full/js/adaptors/liteAdaptor.js');
const { RegisterHTMLHandler } = require('mathjax-full/js/handlers/html.js');
const { AllPackages } = require('mathjax-full/js/input/tex/AllPackages.js');

const ROOT = path.resolve(__dirname, '..', '..');
const APP = path.join(ROOT, 'crates', 'stellar-app');
const SOURCE = path.join(APP, 'equations', 'equations.json');
const OUT_DIR = path.join(APP, 'assets', 'equations');
const RUST_OUT = path.join(APP, 'src', 'equations.rs');

/** Pixels per MathJax `ex`. Computer Modern's x-height is ~0.43 em, so 7.5 px/ex ≈ 17.5 px type. */
const EX_PX = 7.5;

const adaptor = liteAdaptor();
RegisterHTMLHandler(adaptor);
const doc = mathjax.document('', {
  InputJax: new TeX({ packages: AllPackages }),
  OutputJax: new SVG({ fontCache: 'local' }),
});

const equations = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));
const ids = new Set();
fs.mkdirSync(OUT_DIR, { recursive: true });
for (const f of fs.readdirSync(OUT_DIR)) {
  if (f.endsWith('.svg')) fs.unlinkSync(path.join(OUT_DIR, f));
}

const entries = [];
for (const { id, tex } of equations) {
  if (!/^[a-z0-9_]+$/.test(id)) throw new Error(`bad id: ${id}`);
  if (ids.has(id)) throw new Error(`duplicate id: ${id}`);
  ids.add(id);

  const node = doc.convert(tex, { display: true });
  let svg = adaptor.innerHTML(node);
  if (svg.includes('data-mjx-error') || svg.includes('merror')) {
    throw new Error(`TeX error in ${id}: ${tex}`);
  }
  const ex = (name) => {
    const m = svg.match(new RegExp(`${name}="([0-9.]+)ex"`));
    if (!m) throw new Error(`no ${name} in ${id}`);
    return parseFloat(m[1]) * EX_PX;
  };
  const width = ex('width');
  const height = ex('height');
  svg = svg
    .replace(/ width="[0-9.]+ex"/, ` width="${width.toFixed(2)}px"`)
    .replace(/ height="[0-9.]+ex"/, ` height="${height.toFixed(2)}px"`)
    .replace(/ style="[^"]*"/, '')
    .replace(/currentColor/g, '#ffffff');
  if (!svg.includes('xmlns="http://www.w3.org/2000/svg"')) {
    svg = svg.replace('<svg', '<svg xmlns="http://www.w3.org/2000/svg"');
  }
  fs.writeFileSync(path.join(OUT_DIR, `${id}.svg`), svg + '\n');
  entries.push({ id, tex, width, height });
}

const rustString = (s) => JSON.stringify(s); // JSON escapes are valid Rust string escapes here
let rs = `// @generated by tools/equations/render.cjs from equations/equations.json — do not edit.
//! LaTeX equations of the About page, pre-rendered to SVG by MathJax.

/// One typeset equation.
pub struct Equation {
    pub id: &'static str,
    /// LaTeX source (offered via "Copy LaTeX").
    pub tex: &'static str,
    /// SVG with white glyphs, to be tinted with the text colour.
    pub svg: &'static [u8],
    /// Natural size in points.
    pub width: f32,
    pub height: f32,
}

pub static EQUATIONS: &[Equation] = &[
`;
for (const e of entries) {
  rs += `    Equation {
        id: ${rustString(e.id)},
        tex: ${rustString(e.tex)},
        svg: include_bytes!("../assets/equations/${e.id}.svg"),
        width: ${e.width.toFixed(2)},
        height: ${e.height.toFixed(2)},
    },
`;
}
rs += `];

/// Look up an equation by id.
pub fn get(id: &str) -> Option<&'static Equation> {
    EQUATIONS.iter().find(|e| e.id == id)
}
`;
fs.writeFileSync(RUST_OUT, rs);
console.log(`rendered ${entries.length} equations to ${path.relative(ROOT, OUT_DIR)}`);
